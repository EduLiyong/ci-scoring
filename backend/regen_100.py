def generate_sentences(chars):
    sentences = []
    remaining = chars
    sentence_idx = 0
    while remaining > 0:
        if remaining >= 7:
            s = {'chars': 7, 'tone': '中平中仄中平平' if sentence_idx % 3 == 0 else '中仄中平中仄'}
            remaining -= 7
        elif remaining >= 6:
            s = {'chars': 6, 'tone': '中仄中平' if sentence_idx % 3 == 0 else '中平中仄'}
            remaining -= 6
        elif remaining >= 5:
            s = {'chars': 5, 'tone': '中仄平平' if sentence_idx % 3 == 0 else '中平中仄'}
            remaining -= 5
        elif remaining >= 4:
            s = {'chars': 4, 'tone': '仄仄平平' if sentence_idx % 3 == 0 else '中平中仄'}
            remaining -= 4
        else:
            s = {'chars': remaining, 'tone': '中仄中平'[:remaining*2]}
            remaining = 0
        sentence_idx += 1
        sentences.append(s)
    return sentences

def format_entry(c):
    alias_str = str(c['alias']) if c['alias'] else '[]'
    sentences = generate_sentences(c['chars'])
    
    for i, s in enumerate(sentences):
        if i % 3 == 0 and c['chars'] > 20:
            s['rhyme'] = True
            s['rhyme_type'] = '平'
        else:
            s['rhyme'] = False
    
    sentences_str = []
    for s in sentences:
        rhyme_info = f", 'rhyme_type': '{s.get('rhyme_type', '平')}'" if s.get('rhyme') else ""
        sentences_str.append(f"                                         {{'chars': {s['chars']}, 'rhyme': {str(s['rhyme'])}{rhyme_info}, 'tone': '{s['tone']}'}}")
    
    sentences_block = ',\n'.join(sentences_str)
    
    entry = f'''  {{   'alias': {alias_str},
        'description': '{c['desc']}',
        'dynasty': '{c['dynasty']}',
        'id': {c['id']},
        'name': '{c['name']}',
        'patterns': [
            {{   'id': '{c['name']}_zhengti',
                'description': '正体，{c['chars']}字',
                'name': '正体',
                'total_chars': {c['chars']},
                'rhyme_scheme': '',
                'sentences': [
{sentences_block}
            ],
            }},
        ],
  }},'''
    return entry


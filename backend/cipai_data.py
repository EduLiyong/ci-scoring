def get_cipai_by_id(cipai_id):
    for c in CIPAI_DATABASE:
        if c['id'] == cipai_id:
            return c
    return None

def search_cipai(keyword):
    keyword = keyword.lower()
    results = []
    for c in CIPAI_DATABASE:
        if keyword in c['name'].lower():
            results.append(c)
    return results


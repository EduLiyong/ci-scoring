"""测试多个六州歌头文本的字数"""
import re

def zh(text):
    return len(re.findall(r'[\u4e00-\u9fff]', text))

# 刘过《吊武穆》(知乎版本,143字声称)
lg = "中兴诸将，谁是万人英？身草莽，人虽死，气填膺，尚如生。年少起河朔，弓两石，剑三尺；定襄汉，开虢洛，洗洞庭。北望帝京，狡兔依然在，良犬先烹。过旧时营垒，荆鄂有遗民，忆故将军，泪如倾。说当年事，知恨苦；不奉诏，伪耶真？臣有罪，陛下圣，可鉴临，一片心。万古分茅土，终不到，旧奸臣。夜半卷，风吹雨，鹤归来，感君恩。如何一旦，掩抑摧挫，天地无春。但翠烟丹灶，莲社映山青，吴山青。"
print(f"刘过《吊武穆》 知乎版: {zh(lg)}字")

# 李冠《项羽庙》(古诗文网版本,142字)
lg2 = "秦亡草昧，刘项起吞并。鞭寰宇，驱龙虎，扫欃枪，斩长鲸。血染中原战，视余耳，皆鹰犬，平祸乱，归炎汉，势奔倾。兵散月明，风急旌旗乱，刁斗三更。共虞姬相对，泣听楚歌声，玉帐魂惊，泪盈盈。恨花无主，凝愁绪，挥雪刃，掩泉扃。时不利，骓不逝，困阴陵，叱追兵。呜咽摧天地，望归路，忍偷生。功盖世，何处见遗灵。江静水寒烟冷，波纹细、古木凋零。遣行人到此，追念益伤情，胜负难凭。"
print(f"李冠《项羽庙》 古诗文网版: {zh(lg2)}字")

# 刘辰翁《向来人道》(数据库当前版本,143字)
lcy = "向来人道，真个胜幅黎臣。算长淮咫尺，有此奇才谁见。漫咨嗟白草黄沙，斜日孤城，隐约闻弦。更何日、同心结，佩兰纫蕙，酌桂烹藓。想当年、此地经行，几回醉拍阑干。手抚遗踪，凄其欲绝，苦海漫漫。念我萧萧发，霜天老眼，零落故园。雁叫胡笳，蛩吟羌管，数声风叶阑干。"

def check_yunbu_conflict(chars):
    """
    检查多个字是否存在韵部冲突（考虑通用韵组）

    通用韵组内的韵部视为一体，例如"一东"和"二冬"通用，
    则东韵字和冬韵字不视为冲突。

    Args:
        chars: 字列表

    Returns:
        dict: {
            'has_conflict': 是否冲突,
            'yunbu_groups': 韵部分组 {韵部: [字]},
            'common_yunbus': 所有字共有的韵部,
            'compat_yunbus': 通用韵组（所有字共有的通用组交集）,
            'conflict_chars': 冲突的字
        }
    """
    yunbu_groups = {}

    for char in chars:
        yunbus = get_char_yunbu(char)
        for yunbu in yunbus:
            if yunbu not in yunbu_groups:
                yunbu_groups[yunbu] = []
            yunbu_groups[yunbu].append(char)

    # 方法1：严格韵部交集（原逻辑）
    common_yunbus = None
    for char in chars:
        char_yunbus = set(get_char_yunbu(char))
        if not char_yunbus:
            continue
        if common_yunbus is None:
            common_yunbus = char_yunbus
        else:
            common_yunbus = common_yunbus & char_yunbus

    # 方法2：通用韵组交集（新逻辑）
    # 将每个字的韵部扩展为其通用韵组，然后求交集
    compat_yunbus_set = None
    for char in chars:
        char_yunbus = get_char_yunbu(char)
        if not char_yunbus:
            continue
        # 收集该字所有韵部的通用组
        char_compat = set()
        for yb in char_yunbus:
            char_compat.update(get_compatible_yunbus(yb))
        if compat_yunbus_set is None:
            compat_yunbus_set = char_compat
        else:
            compat_yunbus_set = compat_yunbus_set & char_compat

    # 使用通用韵组判断冲突：如果有通用组交集，则不冲突
    has_conflict = len(chars) > 1 and (compat_yunbus_set is None or len(compat_yunbus_set) == 0)

    return {
        'has_conflict': has_conflict,
        'yunbu_groups': yunbu_groups,
        'common_yunbus': list(common_yunbus) if common_yunbus else [],
        'compat_yunbus': sorted(list(compat_yunbus_set)) if compat_yunbus_set else [],
        'conflict_chars': [] if not has_conflict else chars
    }
